/* Published known-answer vectors for every cipher in the repo. This is the
   single source of truth for vector data in the C++ tree, the counterpart of
   the Python suite's tests/vectors.py: the per-cipher suites pull their keys,
   plaintexts and ciphertexts from here, so a vector is only written down
   once.

   Provenance
   ----------
   AES       FIPS-197 C.1/C.2/C.3 and NIST SP 800-38A ECB.
   DES       the classic published single-DES values (the FIPS 46-3
             walkthrough pair, plus the two from the original DES paper's own
             test set). The AABB09182736CCDD entry is widely reproduced but
             does not appear in those sources, so its provenance is
             unconfirmed.
   Blowfish  Schneier's 34-entry official ECB set and the official set_key
             vectors for 1- to 24-byte keys.
   Twofish   the official KATs (Schneier et al., B.2).
   Serpent   the official NESSIE/verified sets for 128/192/256-bit keys as
             published by Biham et al., in little-endian octet order, plus
             two-block ECB and CBC vectors produced with GNU nettle.

   The specifications themselves, and the constant tables each cipher draws
   on, are collected in the repository README under "References and
   attribution". */

/* Collect a static table into the vector the suite runners expect. */
template <size_t N>
inline std::vector<BlockKat> asKats(const BlockKat (&a)[N])
{
	return std::vector<BlockKat>(a, a + N);
}

