void printVec(std::vector<uint8_t> v){
	for (uint8_t* chr = &v[0]; chr< &v[0]+v.size(); ++chr){
        printf("%.2x", *chr);
	printf("\n");
	}
}

uint8_t comprareVector(std::vector<uint8_t> v, std::vector<uint8_t> w)
{
        if (v.size() != w.size())
                return 0;

        for (int i = 0; i < v.size(); ++i)
        {
                if (v[i] != w[i])
                        return 0;
    }   
    return 1;
}




